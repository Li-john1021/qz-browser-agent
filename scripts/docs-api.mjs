/** The locked TS compiler supplies ASTs, documentation and inferred call signatures. */
export function renderApiReference({ rootDir = ROOT, fileSystem } = {}) {
  generateCapabilityCatalogs(rootDir);
  const api = new API({ cwd: rootDir, ...(fileSystem ? { fs: fileSystem } : {}) });
  let snapshot;
  try {
    snapshot = api.updateSnapshot({ openProjects: ["background", "dom"].map(name => resolve(rootDir, `config/typescript/${name}.json`)) });
    const projects = snapshot.getProjects();
    const link = path => relative(resolve(rootDir, "dist/docs"), resolve(rootDir, path)).split(sep).join("/");
    const sections = ["# Extension API reference", "Generated by `npm run docs` from TypeScript contracts. Do not edit this file.",
      `These build-time APIs are experimental; read the [compatibility policy](${link("CONTRIBUTING.md#extension-contracts")}).\nOnly declarations are shown. Runtime ownership and examples remain in the linked source modules.`];
    for (const capability of CAPABILITIES) {
      sections.push(`## ${capability.title}`, `[Runnable example](${link(`tests/fixtures/capabilities/example/${capability.example}`)})`);
      for (const module of capability.modules) {
        const path = `src/${module.path}`;
        const filename = resolve(rootDir, path);
        const project = projects.find(candidate => candidate.program.getSourceFile(filename));
        if (!project) throw new Error(`API source is not included in a TypeScript project: ${path}`);
        const source = project.program.getSourceFile(filename);
        const diagnostics = [...project.program.getSyntacticDiagnostics(filename), ...project.program.getSemanticDiagnostics(filename)];
        if (diagnostics.length) throw new Error(`Cannot document invalid TypeScript: ${path} (${diagnostics.length} diagnostics)`);
        sections.push(`### ${path}`, `[Source](${link(path)})`);
        const declarations = source.statements.filter(node =>
          [SyntaxKind.InterfaceDeclaration, SyntaxKind.TypeAliasDeclaration].includes(node.kind)
          && (module.supportTypes || node.modifiers?.some(modifier => modifier.kind === SyntaxKind.ExportKeyword)),
        );
        if (!declarations.length && !module.functions?.length && !module.methods?.length) throw new Error(`API module contains no contracts: ${path}`);
        // AST boundaries retain field JSDoc and generic helper types without copying implementations.
        if (declarations.length) sections.push(fence(declarations.map(node => source.text.slice(node.pos, node.end).trim()).join("\n\n")));
        for (const name of [...module.functions || [], ...module.methods || []]) {
          const [owner, member] = name.split(".");
          const declaration = source.statements.find(node => node.name?.text === owner);
          const node = member ? declaration?.members.find(node => node.name?.text === member) : declaration;
          if (!node || ![SyntaxKind.FunctionDeclaration, SyntaxKind.MethodDeclaration].includes(node.kind)) {
            throw new Error(`API call signature is missing: ${path}#${name}`);
          }
          const signature = project.checker.getSignatureFromDeclaration(node);
          const type = signature && project.checker.signatureToSignatureDeclaration(signature, SyntaxKind.FunctionType, node, NodeBuilderFlags.NoTruncation);
          if (!type) throw new Error(`Cannot infer API signature: ${path}#${name}`);
          const symbol = project.checker.getSymbolAtLocation(node.name);
          const documentation = symbol && project.checker.getDocumentationCommentOfSymbol(symbol);
          sections.push(`#### ${name}`);
          if (documentation) sections.push(documentation);
          sections.push(fence(`${member ? member : `export const ${name}`}: ${project.emitter.printNode(type)};`));
        }
      }
    }
    return `${sections.join("\n\n")}\n`;
  } finally {
    snapshot?.dispose();
    api.close();
  }
}

const fence = value => `\`\`\`ts\n${value}\n\`\`\``;

export async function generateApiReference({ rootDir = ROOT } = {}) {
  const markdown = renderApiReference({ rootDir });
  const output = resolve(rootDir, "dist/docs/api.md");
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, markdown);
  return output;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateApiReference();
  console.log("Generated dist/docs/api.md");
}
